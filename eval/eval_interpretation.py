N_REPEATS = 3


def run_once(pipeline, case):
    state = {**DEFAULT_SPREAD, **case}
    try:
        out = pipeline._node_interpretation(state)
        interpretation = out["interpretation"]
    except Exception as e:
        return {"error": str(e)}

    judge_prompt = JUDGE_PROMPT.format(
        memory_relevance=case["memory_relevance"],
        tone=case["tone"],
        memory_context=case["memory_context"],
        query=case["query"],
        interpretation=interpretation,
        history_rubric=HISTORY_RUBRIC[case["memory_relevance"]],
        tone_rubric=TONE_RUBRIC,
    )
    try:
        judgment = pipeline.llm.with_structured_output(InterpretationJudgment).invoke(judge_prompt)
    except Exception as e:
        return {"interpretation": interpretation, "error": f"judge failed: {e}"}

    return {"interpretation": interpretation, "judgment": judgment, "error": None}


def stdev(values):
    if len(values) < 2:
        return 0.0
    mean = sum(values) / len(values)
    return (sum((v - mean) ** 2 for v in values) / (len(values) - 1)) ** 0.5


def run_eval():
    pipeline = ArcanaPipeline(project_id=PROJECT_ID, region=REGION)
    print(f"\nEval D: interpretation quality (LLM-as-judge, {N_REPEATS} runs per case)\n")

    all_history_scores, all_tone_scores = [], []

    for case in CASES:
        print(f"[{case['name']}]  target relevance={case['memory_relevance']}  target tone={case['tone']}")
        history_scores, tone_scores, issues_seen = [], [], []

        for run_i in range(N_REPEATS):
            result = run_once(pipeline, case)
            if result.get("error"):
                print(f"  run {run_i+1}: ERROR: {result['error']}")
                continue
            j = result["judgment"]
            history_scores.append(j.history_handling_score)
            tone_scores.append(j.natural_tone_score)
            if j.issues:
                issues_seen.append(j.issues)
            print(f"  run {run_i+1}: history_handling={j.history_handling_score}/5  natural_tone={j.natural_tone_score}/5")

        if history_scores:
            h_mean, h_sd = sum(history_scores) / len(history_scores), stdev(history_scores)
            t_mean, t_sd = sum(tone_scores) / len(tone_scores), stdev(tone_scores)
            stability = "stable" if h_sd <= 0.6 and t_sd <= 0.6 else "UNSTABLE across runs"
            print(f"  -> history: {h_mean:.1f} (sd={h_sd:.2f})   tone: {t_mean:.1f} (sd={t_sd:.2f})   [{stability}]")
            if issues_seen:
                print(f"  issues seen in at least one run: {issues_seen[0]}")
            all_history_scores.extend(history_scores)
            all_tone_scores.extend(tone_scores)
        print()

    if all_history_scores:
        print(f"Overall average history_handling_score: {sum(all_history_scores)/len(all_history_scores):.1f}/5 (n={len(all_history_scores)} runs)")
        print(f"Overall average natural_tone_score:     {sum(all_tone_scores)/len(all_tone_scores):.1f}/5 (n={len(all_tone_scores)} runs)")


if __name__ == "__main__":
    run_eval()
